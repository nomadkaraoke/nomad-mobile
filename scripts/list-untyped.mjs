// Lists gen endpoints whose 200 response has no typed schema (FastAPI routes returning plain dicts).
// Usage: node scripts/list-untyped.mjs > docs/gen-untyped-endpoints.md
import { readFile } from 'node:fs/promises';

const spec = JSON.parse(await readFile(new URL('../openapi/gen.json', import.meta.url), 'utf8'));
const isTyped = (schema) =>
  Boolean(schema && (schema.$ref || (schema.type === 'array' && schema.items?.$ref) || schema.anyOf?.some((s) => s.$ref)));

const rows = [];
for (const [path, ops] of Object.entries(spec.paths)) {
  if (path.startsWith('/api/admin') || path.startsWith('/api/internal')) continue;
  for (const [method, op] of Object.entries(ops)) {
    const ok = op.responses?.['200'] ?? op.responses?.['201'] ?? op.responses?.['202'];
    const schema = ok?.content?.['application/json']?.schema;
    if (!isTyped(schema)) rows.push(`| ${method.toUpperCase()} | \`${path}\` | \`${op.operationId}\` |`);
  }
}

console.log(`# Gen endpoints with untyped responses

Gen endpoints that return untyped dicts. Before the app calls one, add a zod schema in
\`packages/api-gen/src/overrides/\` and file a gen follow-up to add \`response_model\`.

Generated by \`node scripts/list-untyped.mjs\` from \`openapi/gen.json\` (admin/internal routes excluded). ${rows.length} endpoints.

| Method | Path | operationId |
|---|---|---|
${rows.join('\n')}`);
